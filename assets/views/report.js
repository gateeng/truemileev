  parseDesign, defaultDesign, TEMPLATES, ACCENTS, FONTS, SIZES, PAPERS, ORIENTATIONS, MARGINS, LOGO_SIZES,
  LOGO_POSITIONS, LIMITS, paperPx, fitScale, styleText, paperClass, docHtml, fitLogo, chooseLogo,
